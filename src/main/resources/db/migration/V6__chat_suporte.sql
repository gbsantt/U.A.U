CREATE TABLE mensagem_suporte (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitacao_id bigint NOT NULL REFERENCES solicitacao_suporte(id) ON DELETE CASCADE,
 equipe boolean NOT NULL,
 texto varchar(5000) NOT NULL,
 created_at timestamp with time zone NOT NULL
);
CREATE INDEX idx_mensagem_suporte_conversa ON mensagem_suporte(solicitacao_id, id);
